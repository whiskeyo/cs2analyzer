fn export_u32(name: &str, value: u32) -> String {
    format!("export const {name} = {value};\n")
}

fn export_json(name: &str, value: &impl Serialize, pretty: bool) -> Result<String, String> {
    let json = if pretty {
        serde_json::to_string_pretty(value).map_err(|e| e.to_string())?
    } else {
        serde_json::to_string(value).map_err(|e| e.to_string())?
    };
    Ok(format!("export const {name} = {json};\n"))
}

pub(crate) fn module_file(name: &str, body: &str) -> Result<GeneratedFile, String> {
    let mut contents = String::from(GENERATED_BANNER);
    contents.push('\n');
    contents.push_str(body);
    if !body.ends_with('\n') {
        contents.push('\n');
    }
    Ok(GeneratedFile {
        name: name.to_string(),
        contents,
    })
}

/// Write generated modules into `dir`, creating it when needed.
///
/// `hydrate_source` is the hand-written `hydrate.ts` (written only when missing
/// so later tour-loader edits are not clobbered).
pub fn write_tutorial_files(
    dir: &Path,
    files: &[GeneratedFile],
    hydrate_source: Option<&str>,
) -> Result<Vec<(String, usize)>, String> {
    std::fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    remove_stale_shards(dir, files)?;
    let mut written = Vec::new();
    for file in files {
        let path = dir.join(&file.name);
        std::fs::write(&path, file.contents.as_bytes())
            .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        written.push((file.name.clone(), file.contents.len()));
    }
    if let Some(source) = hydrate_source {
        let path = dir.join("hydrate.ts");
        if !path.exists() {
            std::fs::write(&path, source.as_bytes())
                .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            written.push(("hydrate.ts".to_string(), source.len()));
        }
    }
    Ok(written)
}

fn remove_stale_shards(dir: &Path, files: &[GeneratedFile]) -> Result<(), String> {
    for name in STALE_SHARDS {
        if files.iter().any(|file| file.name == name) {
            continue;
        }
        let path = dir.join(name);
        if path.exists() {
            std::fs::remove_file(&path)
                .map_err(|e| format!("cannot remove stale {}: {e}", path.display()))?;
        }
    }
    Ok(())
}

/// Slice, emit, and write. `start` is the cwd (or any path inside the repo).
pub fn write_tutorial_fixture(
    dir: &Path,
    slice: &TutorialSlice,
    shard_after: usize,
    hydrate_source: Option<&str>,
) -> Result<WriteSummary, String> {
    let files = emit_tutorial_files(&slice.sliced, shard_after)?;
    let written = write_tutorial_files(dir, &files, hydrate_source)?;
    Ok(WriteSummary {
        files: written,
        frame_count: slice.sliced.ticks.frame_count,
        player_count: slice.sliced.ticks.player_count,
        round_count: slice.sliced.rounds.len(),
        map_name: slice.sliced.header.map_name.clone(),
        origin_tick: slice.origin_tick,
    })
}

/// `apps/web/src/lib/tutorial` by walking up from `start`, then the cargo workspace.
pub fn discover_tutorial_dir(start: &Path) -> Result<PathBuf, String> {
    let mut cursor = if start.is_absolute() {
        start.to_path_buf()
    } else {
        std::env::current_dir()
            .map_err(|e| format!("cannot read cwd: {e}"))?
            .join(start)
    };
    if cursor.is_file() {
        cursor.pop();
    }
    let mut walk = cursor;
    loop {
        if let Some(found) = tutorial_dir_under(&walk) {
            return Ok(found);
        }
        if !walk.pop() {
            break;
        }
    }
    let crate_root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    if let Some(found) = tutorial_dir_under(&crate_root) {
        return Ok(found);
    }
    Err(
        "cannot find apps/web/src/lib — run from the cs2analyzer repo \
         (walks up from cwd, or uses the cargo workspace root)"
            .into(),
    )
}

fn tutorial_dir_under(root: &Path) -> Option<PathBuf> {
    let lib = root.join("apps/web/src/lib");
    lib.is_dir().then(|| lib.join("tutorial"))
}

#[cfg(test)]
/// Competitive freeze + live play used only when no `.dem` is available.
pub const ESTIMATE_FULL_ROUND_SECONDS: u32 = 115;

#[cfg(test)]
/// Typical GOTV pawn count for size estimates.
pub const ESTIMATE_PLAYER_COUNT: u32 = 10;

/// Frames kept for `seconds` of play at `tick_rate` / `stride`.
#[cfg(test)]
pub fn estimated_frame_count(seconds: u32, tick_rate: f32, stride: u32) -> u32 {
    let hz = tick_rate.max(1.0) / stride.max(1) as f32;
    (seconds as f32 * hz).round() as u32
}

/// Representative SoA buffer (world-ish floats, 64-tick stride labels).
#[cfg(test)]
pub fn synthetic_tick_buffer(frame_count: u32, player_count: u32, stride: u32) -> TickBuffer {
    let n = (frame_count as usize).saturating_mul(player_count as usize);
    let ticks = (0..frame_count).map(|i| i.saturating_mul(stride)).collect();
    TickBuffer {
        frame_count,
        player_count,
        ticks,
        x: vec![1234.5; n],
        y: vec![-890.25; n],
        z: vec![64.0; n],
        yaw: vec![180.0; n],
        health: vec![100; n],
        armor: vec![100; n],
        flags: vec![3; n],
        money: vec![8000; n],
        equip: vec![4700; n],
        gear: vec![72; n],
        primary: vec![7; n],
        secondary: vec![1; n],
        active: vec![7; n],
        clip: vec![30; n],
        reserve: vec![90; n],
    }
}

/// Uncompressed TypeScript bytes for a synthetic tick module (and optional extras).
#[cfg(test)]
pub fn measure_emitted_bytes(files: &[GeneratedFile]) -> usize {
    files.iter().map(|file| file.contents.len()).sum()
}

