//! Compact two-round tutorial Replay → TypeScript under `apps/web/src/lib/tutorial/`.
//!
//! Post-process of the same [`Match`] the JSON dump uses: pick the first live
//! regulation rounds, remap ticks so the slice starts near 0, and emit modules
//! the web hydrate helper can turn into a `Replay`.

use std::path::{Path, PathBuf};

use cs2analyzer::{
    Blind, BombEvent, BuyEvent, ControllerDump, GrenadeThrow, Hurt, Kill, Match, MatchHeader,
    Round, Shot, Side, TickBuffer, DEFAULT_TICK_RATE, FIRST_OVERTIME_ROUND,
};
use serde::Serialize;

/// Live non-knife regulation rounds in the checked-in tutorial fixture.
pub const TUTORIAL_LIVE_ROUNDS: u32 = 2;

/// Snapshot stride when `--stride` is omitted: ~10 Hz on 64-tick GOTV.
const TUTORIAL_SNAPSHOT_HZ: u32 = 10;

/// Keep one tick snapshot every N demo ticks for a compact tutorial parse.
pub const TUTORIAL_TICK_STRIDE: u32 = DEFAULT_TICK_RATE as u32 / TUTORIAL_SNAPSHOT_HZ;

/// Split SoA arrays across `ticks_a.ts` / `ticks_b.ts` above this many values.
pub const TS_SHARD_VALUE_THRESHOLD: usize = 12_000;

pub(crate) const GENERATED_BANNER: &str =
    "/** Generated by `cs2analyzer` tutorial export. Do not edit. */\n";

const STALE_SHARDS: [&str; 2] = ["ticks_a.ts", "ticks_b.ts"];

/// Two-round window after tick remapping.
#[derive(Debug)]
pub struct TutorialSlice {
    pub sliced: Match,
    pub origin_tick: u32,
}

/// One TypeScript module to write (file name relative to the tutorial dir).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    pub name: String,
    pub contents: String,
}

/// Sizes after a successful write.
pub struct WriteSummary {
    pub files: Vec<(String, usize)>,
    pub frame_count: u32,
    pub player_count: u32,
    pub round_count: usize,
    pub map_name: String,
    pub origin_tick: u32,
}

/// First `live_rounds` non-knife regulation rounds, ticks shifted to start near 0.
pub fn slice_tutorial_match(m: &Match, live_rounds: u32) -> Result<TutorialSlice, String> {
    let count = live_rounds.max(1) as usize;
    let selected = select_regulation_rounds(&m.rounds, count)?;
    let start_tick = selected
        .first()
        .map(|r| r.start_tick)
        .ok_or_else(|| "no rounds selected".to_string())?;
    let end_tick = selected
        .last()
        .map(round_window_end)
        .ok_or_else(|| "no rounds selected".to_string())?;
    if end_tick < start_tick {
        return Err("selected rounds have an empty tick window".to_string());
    }
    let origin = start_tick;
    let mut rounds = selected;
    for round in &mut rounds {
        remap_round(round, origin);
    }
    let (score_ct, score_t) = header_scores(&rounds);
    let playback_ticks = end_tick.saturating_sub(origin);
    let tick_rate = m.header.tick_rate.max(1.0);
    let header = MatchHeader {
        map_name: m.header.map_name.clone(),
        tick_rate: m.header.tick_rate,
        tick_stride: m.header.tick_stride,
        duration_s: playback_ticks as f32 / tick_rate,
        playback_ticks,
        team_ct: m.header.team_ct.clone(),
        team_t: m.header.team_t.clone(),
        score_ct,
        score_t,
    };
    Ok(TutorialSlice {
        sliced: Match {
            header,
            players: m.players.clone(),
            rounds,
            ticks: slice_ticks_windows(&m.ticks, &[(start_tick, end_tick)], origin),
            grenades: slice_grenades(&m.grenades, &[(start_tick, end_tick)], origin),
            shots: slice_shots(&m.shots, &[(start_tick, end_tick)], origin),
            kills: slice_kills(&m.kills, &[(start_tick, end_tick)], origin),
            hurts: slice_hurts(&m.hurts, &[(start_tick, end_tick)], origin),
            blinds: slice_blinds(&m.blinds, &[(start_tick, end_tick)], origin),
            bomb_events: slice_bomb_events(&m.bomb_events, &[(start_tick, end_tick)], origin),
            buy_events: slice_buy_events(&m.buy_events, &[(start_tick, end_tick)], origin),
            stats: Vec::new(),
            controller_dump: slice_controller_dump(
                &m.controller_dump,
                &[(start_tick, end_tick)],
                origin,
            ),
        },
        origin_tick: origin,
    })
}

pub(crate) fn select_regulation_rounds(
    rounds: &[Round],
    count: usize,
) -> Result<Vec<Round>, String> {
    let live: Vec<Round> = rounds
        .iter()
        .filter(|round| !round.is_knife && round.number > 0 && round.number < FIRST_OVERTIME_ROUND)
        .cloned()
        .collect();
    if live.len() < count {
        return Err(format!(
            "demo has {} non-knife regulation round{}, need {count} for the tutorial fixture",
            live.len(),
            if live.len() == 1 { "" } else { "s" }
        ));
    }
    Ok(live.into_iter().take(count).collect())
}

pub(crate) fn round_window_end(round: &Round) -> u32 {
    round.end_tick.max(round.playback_end_tick)
}

pub(crate) fn remap_tick(tick: u32, origin: u32) -> u32 {
    tick.saturating_sub(origin)
}

pub(crate) fn remap_round(round: &mut Round, origin: u32) {
    round.start_tick = remap_tick(round.start_tick, origin);
    round.freeze_end_tick = remap_tick(round.freeze_end_tick, origin);
    round.end_tick = remap_tick(round.end_tick, origin);
    if round.playback_end_tick > 0 {
        round.playback_end_tick = remap_tick(round.playback_end_tick, origin);
    }
}

pub(crate) fn header_scores(rounds: &[Round]) -> (i32, i32) {
    let mut score_ct = 0;
    let mut score_t = 0;
    for round in rounds {
        match round.winner {
            Some(Side::Ct) => score_ct += 1,
            Some(Side::T) => score_t += 1,
            None => {}
        }
    }
    (score_ct, score_t)
}

pub(crate) fn slice_ticks_windows(
    buf: &TickBuffer,
    windows: &[(u32, u32)],
    origin: u32,
) -> TickBuffer {
    let player_count = buf.player_count as usize;
    let frames: Vec<usize> = buf
        .ticks
        .iter()
        .enumerate()
        .filter(|(_, tick)| in_any_window(**tick, windows))
        .map(|(index, _)| index)
        .collect();
    TickBuffer {
        frame_count: frames.len() as u32,
        player_count: buf.player_count,
        ticks: frames
            .iter()
            .filter_map(|&frame| buf.ticks.get(frame).copied())
            .map(|tick| remap_tick(tick, origin))
            .collect(),
        x: copy_player_field(&buf.x, &frames, player_count),
        y: copy_player_field(&buf.y, &frames, player_count),
        z: copy_player_field(&buf.z, &frames, player_count),
        yaw: copy_player_field(&buf.yaw, &frames, player_count),
        health: copy_player_field(&buf.health, &frames, player_count),
        armor: copy_player_field(&buf.armor, &frames, player_count),
        flags: copy_player_field(&buf.flags, &frames, player_count),
        money: copy_player_field(&buf.money, &frames, player_count),
        equip: copy_player_field(&buf.equip, &frames, player_count),
        gear: copy_player_field(&buf.gear, &frames, player_count),
        primary: copy_player_field(&buf.primary, &frames, player_count),
        secondary: copy_player_field(&buf.secondary, &frames, player_count),
        active: copy_player_field(&buf.active, &frames, player_count),
        clip: copy_player_field(&buf.clip, &frames, player_count),
        reserve: copy_player_field(&buf.reserve, &frames, player_count),
    }
}

fn copy_player_field<T: Copy + Default>(
    src: &[T],
    frames: &[usize],
    player_count: usize,
) -> Vec<T> {
    let mut out = Vec::with_capacity(frames.len().saturating_mul(player_count));
    for &frame in frames {
        let base = frame.saturating_mul(player_count);
        for offset in 0..player_count {
            out.push(src.get(base + offset).copied().unwrap_or_default());
        }
    }
    out
}

fn in_window(tick: u32, start_tick: u32, end_tick: u32) -> bool {
    tick >= start_tick && tick <= end_tick
}

pub(crate) fn in_any_window(tick: u32, windows: &[(u32, u32)]) -> bool {
    windows
        .iter()
        .any(|&(start_tick, end_tick)| in_window(tick, start_tick, end_tick))
}

/// Seconds after freeze end, clamped to the same prefs range as the viewer.
pub fn clamp_habits_window_sec(value: u32) -> u32 {
    value.clamp(
        cs2analyzer::SERIES_HABITS_WINDOW_MIN_SECONDS,
        cs2analyzer::SERIES_HABITS_WINDOW_MAX_SECONDS,
    )
}

/// Inclusive `[freeze_end, freeze_end + window]` clipped to the round end.
pub fn habits_window_for_round(round: &Round, tick_rate: f32, window_sec: u32) -> (u32, u32) {
    let start = if round.freeze_end_tick > 0 {
        round.freeze_end_tick
    } else {
        round.start_tick
    };
    let span = (clamp_habits_window_sec(window_sec) as f32 * tick_rate.max(1.0)).round() as u32;
    let end = start.saturating_add(span).min(round_window_end(round));
    (start, end)
}

pub(crate) fn slice_grenades(
    grenades: &[GrenadeThrow],
    windows: &[(u32, u32)],
    origin: u32,
) -> Vec<GrenadeThrow> {
    grenades
        .iter()
        .filter(|throw| in_any_window(throw.start_tick, windows))
        .cloned()
        .map(|mut throw| {
            throw.start_tick = remap_tick(throw.start_tick, origin);
            throw.detonate_tick = remap_tick(throw.detonate_tick, origin);
            throw.end_tick = remap_tick(throw.end_tick, origin);
            for point in &mut throw.points {
                point.tick = remap_tick(point.tick, origin);
            }
            for fire in &mut throw.fires {
                fire.start_tick = remap_tick(fire.start_tick, origin);
                fire.end_tick = remap_tick(fire.end_tick, origin);
            }
            throw
        })
        .collect()
}

